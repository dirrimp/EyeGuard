#!/usr/bin/env python3
"""Generates android/onn-monitor/src/com/eyeguard/onn/Recipients.java from config.yaml: Dad's offline key FIRST, then every
approved extra recipient (encryption.recipients), in the same order the Mac's uploader uses. The Onn compiles these PUBLIC keys
into the APK, so adding or removing a viewer is a reviewed config PR plus a regenerated file plus a rebuild.
  python3 tools/gen_onn_recipients.py            write the file
  python3 tools/gen_onn_recipients.py --check    exit 1 if the committed file differs from what config.yaml produces
Run with the app's Python (it has pyyaml and cryptography)."""
import hashlib, sys
from pathlib import Path
import yaml
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "android/onn-monitor/src/com/eyeguard/onn/Recipients.java"
MAX = 8

def build() -> str:
    enc = yaml.safe_load((ROOT / "config.yaml").read_text())["encryption"]
    items = [("Dad (offline key, recipient #1)", enc["public_key_pem"])]
    items += [(r["label"], r["public_key_pem"]) for r in (enc.get("recipients") or [])]
    seen, rows = set(), []
    for label, pem in items:
        pk = serialization.load_pem_public_key(pem.encode())
        if not isinstance(pk, rsa.RSAPublicKey) or pk.key_size < 2048:
            raise SystemExit(f"recipient {label!r}: not RSA >= 2048 bits")
        der = pk.public_bytes(serialization.Encoding.DER, serialization.PublicFormat.SubjectPublicKeyInfo)
        kid = hashlib.sha256(der).hexdigest()[:16]
        if kid in seen:
            continue
        seen.add(kid)
        rows.append((label, kid, pem.strip()))
    if not 1 <= len(rows) <= MAX:
        raise SystemExit(f"need 1..{MAX} distinct recipients, got {len(rows)}")
    out = ["// GENERATED by tools/gen_onn_recipients.py from config.yaml. DO NOT EDIT BY HAND: tests/test_onn_egf2_static.py fails if this",
           "// file differs from what config.yaml produces. PUBLIC keys only. The first is Dad's offline key (always recipient #1).",
           "package com.eyeguard.onn;", "", "final class Recipients {", "    private Recipients() {}", "",
           "    /** Human labels, same order as PEMS (never sent anywhere). */", "    static final String[] LABELS = {"]
    out += [f'        "{l.replace(chr(34), chr(39))}",' for l, _, _ in rows]
    out += ["    };", "", "    /** Key ids (first 8 bytes of SHA-256 of the DER public key, hex), same order. */", "    static final String[] KEY_IDS = {"]
    out += [f'        "{k}",' for _, k, _ in rows]
    out += ["    };", "", "    static final String[] PEMS = {"]
    for _, _, p in rows:
        out.append("        " + " +\n        ".join('"' + line + '\\n"' for line in p.splitlines()) + ",")
    out += ["    };", "}", ""]
    return "\n".join(out)

if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
